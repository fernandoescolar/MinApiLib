namespace MinApiLib.Endpoints;

[Generator]
public class EndpointSourceGenerator : IIncrementalGenerator
{
    private const string EndpointInterfaceName = "IEndpoint";
    private const string EndpointAssemblyName = "MinApiLib.Endpoints";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // The pipeline carries names instead of symbols, so the output is only regenerated when they change.
        var endpoints = context.SyntaxProvider.CreateSyntaxProvider(
                                    static (node, _) => node is ClassDeclarationSyntax or RecordDeclarationSyntax,
                                    static (ctx, ct) => GetEndpointName(ctx.SemanticModel.GetDeclaredSymbol(ctx.Node, ct) as INamedTypeSymbol))
                               .Where(static name => name is not null)
                               .Collect();

        context.RegisterSourceOutput(endpoints, static (spc, names) => Execute(names, spc));
    }

    private static string? GetEndpointName(INamedTypeSymbol? symbol)
        => symbol is not null && IsMappable(symbol)
            ? symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
            : null;

    // Must match the constraints of MapEndpoint<T>(), or the generated code doesn't compile.
    private static bool IsMappable(INamedTypeSymbol symbol)
        => symbol.TypeKind == TypeKind.Class
        && !symbol.IsAbstract
        && !symbol.IsGenericType
        && IsAccessible(symbol)
        && symbol.InstanceConstructors.Any(x => x.Parameters.Length == 0 && x.DeclaredAccessibility == Accessibility.Public)
        && symbol.AllInterfaces.Any(x => x.Name == EndpointInterfaceName && x.ContainingAssembly.Name == EndpointAssemblyName);

    private static bool IsAccessible(INamedTypeSymbol symbol)
    {
        for (var type = symbol; type is not null; type = type.ContainingType)
        {
            if (type.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedOrInternal))
            {
                return false;
            }
        }

        return true;
    }

    private static void Execute(ImmutableArray<string?> names, SourceProductionContext context)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("using Microsoft.AspNetCore.Builder;");
        sb.AppendLine("using Microsoft.AspNetCore.Routing;");
        sb.AppendLine();
        sb.AppendLine("namespace MinApiLib.Endpoints;");
        sb.AppendLine();
        sb.AppendLine("internal static class MinApiLibExtensions");
        sb.AppendLine("{");
        sb.AppendLine("    public static RouteGroupBuilder MapAotEndpoints(this IEndpointRouteBuilder endpoints)");
        sb.AppendLine("    {");
        sb.AppendLine("        var group = endpoints.MapGroup(\"/\");");

        // A partial type has one declaration per part.
        foreach (var name in names.Distinct().OrderBy(x => x, System.StringComparer.Ordinal))
        {
            sb.AppendLine($"        group.MapEndpoint<{name}>();");
        }

        sb.AppendLine("        return group;");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        context.AddSource("MinApiLibExtensions.g.cs", sb.ToString());
    }
}
